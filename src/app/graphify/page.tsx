function hasHelpFlag(path?: string | null): boolean {
  if (!path) return false;
  const raw = path.trim();
  return raw === "--help" || raw === "-h" || raw === "";
}

export default function GraphifyPage({
  params,
}: {
  params: { segments: string[] };
}) {
  const helpFromSegments = params.segments.includes("help");
  const pathFromSegments = params.segments.find(
    (seg) => !hasHelpFlag(seg) && seg !== "graphify"
  );

  const showHelp = helpFromSegments;
  const pathInput = pathFromSegments || "";

  const [result, setResult] = useState<string | null>(null);

  const handleRun = async () => {
    if (!pathInput.trim()) {
      window.alert("Please provide a path or URL");
      return;
    }
    setResult(`Graphify pipeline running on: ${pathInput.trim()}\n\n`);
    setResult((prev) => prev + "Pipeline execution started...\n");
  };

  if (showHelp) {
    return (
      <div className="min-h-screen bg-background p-8">
        <Card className="max-w-3xl mx-auto p-6">
          <h2 className="text-2xl font-bold mb-4">graphify Usage</h2>
          <p className="text-sm text-muted-foreground leading-relaxed">
            {USAGE_BLOCK}
          </p>
          <Button
            onClick={() => window.history.back()}
            className="mt-4 w-full"
          >
            Back to tools
          </Button>
        </Card>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-background p-8">
      <Card className="max-w-4xl mx-auto p-6">
        <h2 className="text-2xl font-bold mb-4">graphify</h2>

        {pathInput ? (
          <form onSubmit={handleRun} className="mt-6">
            <p className="text-sm text-muted-foreground">
              Running graphify on: <code>{pathInput}</code>
            </p>
            <Button type="submit" disabled={false}>Run</Button>
          </form>
        ) : (
          <div>
            <label className="block text-sm font-medium mb-2">
              Path or URL
              <span className="text-muted-foreground">
                (e.g., `.`, `./docs`, `https://github.com/owner/repo`)
              </span>
            </label>
            <Input
              value={pathInput}
              onChange={() => {}}
              placeholder="."
              required
            />
            <Button type="submit" disabled={true}>Run graphify</Button>
          </div>
        )}

        {result && (
          <Card className="mt-6 p-4">
            <pre className="text-xs text-muted-foreground whitespace-pre-wrap">{result}</pre>
          </Card>
        )}
      </Card>
    </div>
  );
}